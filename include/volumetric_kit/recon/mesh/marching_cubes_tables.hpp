/// @file mesh/marching_cubes_tables.hpp
/// @brief The marching-cubes lookup tables: the 256-case triangle table plus
/// the
///        cube's corner and edge topology.
///
/// These are the standard Paul Bourke / NVIDIA marching-cubes tables, ported
/// verbatim from the prior engine so the extracted surface inherits its proven
/// winding and sign convention. They are the single source of the tables across
/// CPU and GLSL: the host uploads them into a device storage buffer that the
/// @c marching_cubes.comp kernel indexes, rather than the shader carrying its
/// own copy -- the same one-definition discipline the volume tier applies to
/// its POD layouts.
///
/// Conventions (must be read together with the kernel):
/// - **Corner numbering** (@ref kCornerOffset): corner 0 is the cell's base
///   sample `(0,0,0)`; the bottom face (z=0) runs CCW 0,1,2,3 and the top face
///   (z=1) runs 4,5,6,7 above it. The cube index sets bit `i` when corner `i`
///   is inside the surface (`sdf[i] < iso`).
/// - **Edge numbering** (@ref kEdgeToVert): edges 0-3 are the bottom face, 4-7
///   the top face, 8-11 the verticals; each entry is the edge's two endpoint
///   corners. Endpoint order is symmetric for interpolation -- winding is
///   governed entirely by @ref kTriTable.
/// - **@ref kTriTable**: one row per 256 corner-sign combinations, listing edge
///   indices in triples (one triangle each) terminated by `-1`; up to 5
///   triangles (15 entries) per cell.

