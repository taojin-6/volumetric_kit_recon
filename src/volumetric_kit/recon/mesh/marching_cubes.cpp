// The public entry point a diagnostic reports under. Every extract funnels
// through extract_device_impl, so without this the whole tier would name that
// -- or, as it did until this was threaded, a `MarchingCubes::extract` the
// header no longer declares, leaving a user with a message they cannot grep
// back to any of the entry points. Carried as a parameter rather than a member
// so it cannot outlive the call it describes.
constexpr const char* kEntryHost = "MarchingCubes::extract_host";
constexpr const char* kEntryDevice = "MarchingCubes::extract_device";
constexpr const char* kEntryRecord = "MarchingCubes::record_extract";
constexpr const char* kEntryFinish = "MarchingCubes::finish";

// Worst-case triangles a single marching-cubes cell can emit (5 per the table).
constexpr std::uint64_t kMaxTrisPerCell = 5;

// The draw command is an ABI across three languages now -- the host resets it
// and reads it back, the GLSL kernel aliases its first field as the append
// atomic (`buffer DrawCommand { uint index_count; ... }`, offset 0 under scalar
// block layout), and the renderer's vkCmdDrawIndexedIndirect consumes the whole
// struct. Vulkan fixes this layout, but the 4-byte fill in
// disarm_indirect_command() and the IndirectWords readback assume it here, and
// this file already pins every other cross-language struct the same way.
static_assert(sizeof(VkDrawIndexedIndirectCommand) == 20,
              "VkDrawIndexedIndirectCommand must be 20 bytes -- the kernel's "
              "DrawCommand mirror and the host reset/readback assume it");
static_assert(offsetof(VkDrawIndexedIndirectCommand, indexCount) == 0,
              "indexCount must be field 0 -- the kernel's append atomic bumps "
              "it through a storage binding at offset 0, and the host clamps "
              "it with a 4-byte write to the start of the buffer");

// Triangles per active block the first extract plans for, before any
// measurement is available. A real scan measures 54-68 (Replica room0) against
// the 5*block_size^3 worst case -- 2560 for the default 8-voxel block, ~40x
// higher -- and the estimate self-corrects from the first completed extract, so
// this only has to be the right order of magnitude. Guessing low costs one
// extra dispatch on the first call; guessing high costs resident memory for the
// extractor's whole lifetime, since the arena never shrinks.
constexpr std::uint64_t kSeedTrisPerBlock = 64;

// Vertices per 1000 triangles to assume before anything has been measured.
//
// Deliberately OPTIMISTIC -- below the ~750 in-block sharing settles at --
// because the arena is grow-only: a first extract that over-allocates never
// gives the memory back, which would defeat the point. Under-shooting instead
// costs one refit dispatch, which is the backstop the capacity plan already
// has. Unshared extracts never consult this; they know the answer is 3000.
constexpr std::uint32_t kSeedVertsPer1000 = 700;

// Cells the sharing kernel's shared owned-edge table holds -- block_size 8.
//
// Mirrors kMaxSharedCells in marching_cubes_sparse_shared.comp, and a comment
// is all that could tie a C++ constant to a GLSL one. So the drift is
// *detected* rather than asserted: the kernel reports whether it actually
// shared
// (`sharing_applied`, byte 24 of the command buffer) and extract_device fails
// if it did not. Raising this alone would otherwise admit a block the kernel
// silently meshes unshared -- correct geometry, feature quietly gone. The other
// direction (lowering this alone) merely refuses grids the kernel could handle,
// and the kernel's own `vpb <= kMaxSharedCells` test is what keeps either from
// indexing past the shared array.
constexpr std::uint32_t kMaxSharedCells = 512;

// A corner with weight below this is treated as unintegrated (the kernel's test
// is `weight < weight_threshold`), and any cell touching it is skipped. The
// volume tier defines it, so the codec's observed mask reads the same value.
// The `tsdf` tier will surface this as a tunable knob.
constexpr float kWeightThreshold = volume::kObservedWeight;

// The lookup tables, flattened for upload -- byte-identical to the GLSL
// `Tables` block (scalar layout, all-int so std430 and scalar agree). One
// definition of the tables (the constexpr arrays in the header) feeds both
// sides.
struct McTables {
  std::int32_t tri_table[256 * 16];
  std::int32_t corner_offset[8 * 3];
  std::int32_t edge_to_vert[12 * 2];
};
static_assert(sizeof(McTables) ==
                  (256 * 16 + 8 * 3 + 12 * 2) * sizeof(std::int32_t),
              "McTables must be tightly packed for the shader ABI");

// The push-constant block the sparse kernel reads (mirrors `PushConstants` in
// marching_cubes_sparse.comp under scalar layout). The grid geometry rides here
// (block_size / voxel_size); the block coordinates and per-voxel data come
// through the bound buffers.
struct SparsePushConstants {
  std::int32_t block_size;
  std::int32_t voxels_per_block;
  float voxel_size;
  float iso;
  std::uint32_t num_active_blocks;
  std::uint32_t capacity;
  float weight_threshold;
  std::uint32_t has_color;  // 0 = no color attribute; vertices get opaque white
  // Vertices the arena holds. Its own budget rather than `capacity * 3`: once
  // cells share a vertex the two stop being proportional, and sizing the arena
  // from the triangle plan is exactly what would make sharing save nothing.
  //
  // Defaulted and assigned by name, not filled positionally, for the same
  // reason the three below are: adjacent same-typed scalars make a positional
  // slip compile clean.
  std::uint32_t vertex_capacity = 0;
  // The hash-table shape, for the kernel's on-device neighbour probe. The
  // sparse kernel resolves the 2x2x2 neighbourhood itself now, so it needs to
  // traverse the table the same way the volume tier does.
  //
  // Defaulted, and deliberately NOT filled from the aggregate initializer at
  // the dispatch: these three are same-typed adjacent scalars copied out of
  // another tier's private table shape, so a positional transposition of
  // num_buckets and bucket_size would satisfy every static_assert below (both
  // int32, at 32 and 36) and compile. They are assigned by name instead.
  std::int32_t num_buckets = 0;
  std::int32_t bucket_size = 0;
  std::int32_t max_chain = 0;
  // Block slots this grid's heap holds (VoxelGridParams::num_blocks). The
  // extract binds only a list this grid's map compacted
  // (check_device_block_subset), so every ptr is one the heap handed out;
  // this is a one-comparison-per-workgroup guard against a corrupted list,
  // since robustBufferAccess is enabled nowhere. Assigned by name, like the
  // four above.
  std::uint32_t num_block_slots = 0;
  // The first active block this dispatch covers, written by
  // recon::detail::dispatch_items.
  std::uint32_t item_base = 0;
};
// Pin every field offset (all 4-byte scalars): a same-size reorder would keep
// sizeof unchanged but silently drift the host<->GLSL push-constant ABI, so
// guard each one.
static_assert(sizeof(SparsePushConstants) == 56,
              "SparsePushConstants must be 56 bytes");
static_assert(offsetof(SparsePushConstants, vertex_capacity) == 32,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, block_size) == 0,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, voxels_per_block) == 4,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, voxel_size) == 8,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, iso) == 12,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, num_active_blocks) == 16,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, capacity) == 20,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, weight_threshold) == 24,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, has_color) == 28,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, num_buckets) == 36,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, bucket_size) == 40,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, max_chain) == 44,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, num_block_slots) == 48,
              "SparsePushConstants layout drift");
static_assert(offsetof(SparsePushConstants, item_base) == 52,
              "SparsePushConstants layout drift");

// The command buffer: the draw command plus two words of recon scratch,
// immediately past it. Keeping them in this buffer costs no second allocation
// per ring slot and leaves a well-formed command at offset 0, which is all
// vkCmdDrawIndexedIndirect binds. The host resets it and reads it back whole,
// in one transfer each way.
struct IndirectWords {
  VkDrawIndexedIndirectCommand command;
  // The vertex counter, which the sharing kernel allocates through. It cannot
  // be derived from indexCount any more -- that held only while every
  // triangle owned three private vertices.
  std::uint32_t vertex_count;
  // The sharing kernel's report that it really did share (see
  // kMaxSharedCells). This and vertex_count are written only by
  // marching_cubes_sparse_shared.comp; the default kernel leaves them at the
  // host's reset.
  std::uint32_t sharing_applied;
};
// Packed, as the kernels' scalar-layout mirror assumes.
static_assert(sizeof(IndirectWords) == sizeof(VkDrawIndexedIndirectCommand) +
                                           2 * sizeof(std::uint32_t),
              "IndirectWords must mirror the command buffer's layout");
constexpr VkDeviceSize kIndirectBufferBytes = sizeof(IndirectWords);

// What the finalize (mc_finalize.comp) writes into an extract's result slot,
// whole.
struct McResults {
  std::uint32_t index_count;      // the field's, past the capacity included
  std::uint32_t vertex_count;     // the sharing kernel's
  std::uint32_t sharing_applied;  // the sharing kernel's report
  std::uint32_t meshed;           // the blocks meshed
  std::uint32_t opened;           // whether the gate was open
};
static_assert(sizeof(McResults) == 4 * 5,
              "McResults is five words, as mc_finalize.comp writes it");

