// mc_args.comp's word index that names no word.
constexpr std::uint32_t kNoWord = ~0u;

// The sparse kernel's push constants for @p blocks listed blocks of @p grid
// at @p iso, into a slot that meshes @p capacity triangles and holds
// @p vertex_capacity vertices.
SparsePushConstants sparse_push(const volume::VoxelBlockGrid& grid, float iso,
                                std::uint32_t blocks, std::uint32_t capacity,
                                std::uint32_t vertex_capacity) {
  const volume::VoxelGridParams& gp = grid.grid();
  SparsePushConstants push{
      gp.block_size,    gp.voxels_per_block,
      gp.voxel_size,    iso,
      blocks,           capacity,
      kWeightThreshold, grid.has_attribute("color") ? 1u : 0u};
  // Assigned by name, not appended to the aggregate above. These three are
  // same-typed adjacent scalars copied out of another tier's private table
  // shape, so a transposition of num_buckets and bucket_size would keep every
  // offsetof static_assert true (both are int32 at 32/36) and still compile,
  // and the kernel would then hash into `h % 50` over a 30000-bucket table --
  // every probe resolving against the wrong bucket, every seam losing its
  // surface, Status::ok.
  push.num_buckets = gp.num_buckets;
  push.bucket_size = gp.bucket_size;
  push.max_chain = gp.max_chain;
  // Assigned by name for the same reason the three above are: they are
  // same-typed adjacent scalars, so a positional slip would compile.
  push.vertex_capacity = vertex_capacity;
  push.num_block_slots = static_cast<std::uint32_t>(gp.num_blocks);
  return push;
}

// The extracts' result slots: the batch in flight and the one recorded.
constexpr std::uint32_t kResultSlots = 2;

// How long finish waits, after the extract's batch has resolved, for the
// timeline value it set: a driver may signal the fence first.
constexpr std::uint64_t kSignalGraceNs = 1'000'000'000ull;

// Bytes a vertex arena needs to hold @p vertex_capacity VERTICES.
//
// Vertices, not triangles. The two were interchangeable while every triangle
// owned three private ones, and the whole point of vertex sharing is that they
// stop being: the arena is now sized by its own budget and the index run by the
// triangle count, independently.
std::uint64_t arena_bytes_for(std::uint64_t vertex_capacity) {
  return vertex_capacity * sizeof(Vertex);
}

// Bytes the index run needs to hold @p triangle_capacity triangles.
std::uint64_t index_run_bytes_for(std::uint64_t triangle_capacity) {
  return triangle_capacity * kIndicesPerTriangle * sizeof(std::uint32_t);
}

// The most VERTICES an arena may hold under a binding-range limit. Never zero
// for any conformant device -- Vulkan's guaranteed floor of 2^27 covers
// 2097152 vertices at 64 B each.
std::uint64_t max_vertices_for(std::uint64_t max_range) {
  return max_range / sizeof(Vertex);
}

// The most triangles an INDEX RUN may hold under the same limit. Not the whole
// triangle ceiling: the vertices those triangles need have to fit the arena
// too, which at three private vertices each is 16x tighter. plan_capacity takes
// the minimum of the two -- taking this one alone is what let a *predicted*
// capacity be rejected by ensure_output_buffers instead of clamped, which fails
// an extractor permanently (the density is recorded only on success, and a
// scan's active set only grows).
std::uint64_t max_triangles_for(std::uint64_t max_range) {
  return max_range / (kIndicesPerTriangle * sizeof(std::uint32_t));
}

// Stopwatch for the opt-in ExtractTimings: host wall clock alone. Reading the
// clock is cheap, but it is skipped entirely when the caller wants no
// measurement, so the untimed path costs one branch per phase. The device
// halves are the stage rows' (extract_device's metrics), tiled inside the
// submits the phases already make.
class PhaseClock {
 public:
  explicit PhaseClock(bool enabled) : enabled_(enabled) { restart(); }

  void restart() {
    if (enabled_) start_ = std::chrono::steady_clock::now();
  }

  // Milliseconds since the last restart, then restart for the next phase.
  double lap() {
    if (!enabled_) return 0.0;
    const auto now = std::chrono::steady_clock::now();
    const double ms =
        std::chrono::duration<double, std::milli>(now - start_).count();
    start_ = now;
    return ms;
  }

 private:
  bool enabled_;
  std::chrono::steady_clock::time_point start_{};
};

