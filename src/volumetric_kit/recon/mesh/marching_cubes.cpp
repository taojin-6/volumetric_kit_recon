// The draw command plus two words of recon scratch, starting at byte 20,
// immediately past the 20-byte VkDrawIndexedIndirectCommand. Keeping them in
// this buffer costs no second allocation per ring slot and leaves a well-formed
// command at offset 0, which is all vkCmdDrawIndexedIndirect binds.
//   * The vertex counter, which the sharing kernel allocates through. It cannot
//     be derived from indexCount any more -- that held only while every
//     triangle owned three private vertices.
//   * The sharing kernel's report that it really did share (see
//     kMaxSharedCells).
// Both are written only by marching_cubes_sparse_shared.comp; the default
// kernel leaves them at the host's reset.
constexpr VkDeviceSize kVertexCountOffset =
    sizeof(VkDrawIndexedIndirectCommand);
constexpr VkDeviceSize kSharingAppliedOffset =
    kVertexCountOffset + sizeof(std::uint32_t);
//   * Blocks an incremental dispatch actually re-meshed, which is the number
//     the whole feature trades against and the one thing about it the host
//     cannot derive: the dilation from the changed set to the re-mesh set
//     happens on-device, off shared memory. Bumped once per re-meshed
//     workgroup by the default kernel and only while pc.incremental is set --
//     a full pass re-meshes its whole active set, which the host already knows,
//     and 107k atomics to restate it is not free.
constexpr VkDeviceSize kRemeshedBlocksOffset =
    kSharingAppliedOffset + sizeof(std::uint32_t);
constexpr VkDeviceSize kIndirectBufferBytes =
    kRemeshedBlocksOffset + sizeof(std::uint32_t);

// Read one of the scratch words back out of the command buffer.
std::uint32_t read_scratch(const Buffer& indirect, VkDeviceSize offset) {
  std::uint32_t value = 0;
  std::memcpy(&value, static_cast<const std::byte*>(indirect.mapped()) + offset,
              sizeof(value));
  return value;
}

// Bytes a vertex arena needs to hold @p vertex_capacity VERTICES.
//
// Vertices, not triangles. The two were interchangeable while every triangle
// owned three private ones, and the whole point of vertex sharing is that they
// stop being: the arena is now sized by its own budget and the index run by the
// triangle count, independently.
std::uint64_t arena_bytes_for(std::uint64_t vertex_capacity) {
  return vertex_capacity * sizeof(Vertex);
}

// Bytes the index run needs to hold @p triangle_capacity triangles.
std::uint64_t index_run_bytes_for(std::uint64_t triangle_capacity) {
  return triangle_capacity * kIndicesPerTriangle * sizeof(std::uint32_t);
}

// The most VERTICES an arena may hold under a binding-range limit. Never zero
// for any conformant device -- Vulkan's guaranteed floor of 2^27 covers
// 2097152 vertices at 64 B each.
std::uint64_t max_vertices_for(std::uint64_t max_range) {
  return max_range / sizeof(Vertex);
}

// The most triangles an INDEX RUN may hold under the same limit. Not the whole
// triangle ceiling: the vertices those triangles need have to fit the arena
// too, which at three private vertices each is 16x tighter. plan_capacity takes
// the minimum of the two -- taking this one alone is what let a *predicted*
// capacity be rejected by ensure_output_buffers instead of clamped, which fails
// an extractor permanently (the density is recorded only on success, and a
// scan's active set only grows).
std::uint64_t max_triangles_for(std::uint64_t max_range) {
  return max_range / (kIndicesPerTriangle * sizeof(std::uint32_t));
}

// Read the atomic triangle count back and copy the emitted vertices into a
// Mesh with the trivial 0,1,2,... index run (independent triangles; a later
// shared-vertex dedup can shrink `vertices` without changing the Mesh
// contract). The dense extract's readback; the sparse path leaves its result on
// the device and downloads it separately.
Mesh collect_mesh(const Buffer& vertices, const Buffer& indirect,
                  std::uint32_t capacity,
                  std::uint32_t* emitted_out = nullptr) {
  // The counter *is* the command's indexCount, so triangles are a third of it
  // -- see mcEmitCell, which adds kIndicesPerTriangle per triangle.
  VkDrawIndexedIndirectCommand command{};
  std::memcpy(&command, indirect.mapped(), sizeof(command));
  std::uint32_t emitted = command.indexCount / kIndicesPerTriangle;
  // The dense path is worst-case sized, so the kernel never drops -- but the
  // count is a device write, and this clamp is what keeps the copy below inside
  // the arena regardless.
  emitted = std::min(emitted, capacity);
  if (emitted_out != nullptr) *emitted_out = emitted;

  const auto vertex_count =
      static_cast<std::size_t>(emitted) * kIndicesPerTriangle;
  Mesh mesh;
  // TODO(mesh): resize() zero-initializes the vector and the memcpy below
  // immediately overwrites it -- two passes over the whole readback. There is
  // no resize-without-init on std::vector; revisit if the download shows up in
  // an ExtractTimings profile.
  mesh.vertices.resize(vertex_count);
  if (vertex_count > 0) {
    std::memcpy(mesh.vertices.data(), vertices.mapped(),
                vertex_count * sizeof(Vertex));
  }
  mesh.indices.resize(vertex_count);
  std::iota(mesh.indices.begin(), mesh.indices.end(), std::uint32_t{0});
  return mesh;
}

// Stopwatch for the opt-in ExtractTimings. Reading the clock is cheap, but it
// is skipped entirely when the caller wants no measurement, so the untimed path
// costs one branch per phase.
//
// TODO(mesh): give these phases a device half, but NOT one timed submit each.
// A timed submit costs ~0.13 ms more than an untimed one on MoltenVK (the first
// vkCmdWriteTimestamp in a command buffer -- measured, see the 2026-08-09
// timings decision), and four of six phases here run at or under that, so
// per-phase timing would report the profiler rather than the extract. Bracket
// several dispatches inside one timed submit with GpuTimer::begin/end and a
// single resolve() after it, which is the shape Device::submit_single_time's
// doc points at.
class PhaseClock {
 public:
  explicit PhaseClock(bool enabled) : enabled_(enabled) { restart(); }

  void restart() {
    if (enabled_) start_ = std::chrono::steady_clock::now();
  }

  // Milliseconds since the last restart, then restart for the next phase.
  double lap() {
    if (!enabled_) return 0.0;
    const auto now = std::chrono::steady_clock::now();
    const double ms =
        std::chrono::duration<double, std::milli>(now - start_).count();
    start_ = now;
    return ms;
  }

 private:
  bool enabled_;
  std::chrono::steady_clock::time_point start_{};
};

