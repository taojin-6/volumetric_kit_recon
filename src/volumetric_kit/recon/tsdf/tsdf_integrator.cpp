// Local group size, matching `layout(local_size_x = 256)` in the kernel.
constexpr std::uint32_t kLocalSize = 256;

// What one dispatch does with its frame: Dynamic's clear and the fuse, or
// either alone for a Dynamic set of several frames (see integrate).
enum class Pass { Both, Clear, Fuse };

// The push-constant block (mirrors `PushConstants` in tsdf_common.glsl): the
// grid, the active-block count, the fusion weight cap, the integration mode,
// two color flags, the tick, the coverage flag and fuse_only, shared by the
// integrate and clear kernels. `has_color` fuses the supplied color frame;
// `has_color_attr` says binding 6 is the grid's real color attribute (so
// dynamic can clear a stale color even on a depth-only frame) -- the two differ
// because a grid can carry `color` without a color image arriving this call.
// The camera rides the SSBO as DepthCameraParams verbatim -- the kernel
// derives world -> camera from its rigid cam_to_world, so there is no separate
// pre-inverted per-dispatch struct.
struct PushConstants {
  VoxelGridParams grid;
  std::uint32_t num_active_blocks;
  float max_weight;
  std::uint32_t mode;       // tsdf::IntegrationMode (0 = classic, 1 = dynamic).
  std::uint32_t has_color;  // 0 = depth only; 1 = fuse the color frame.
  std::uint32_t has_color_attr;  // 1 = binding 6 is the grid's color attribute.
  std::uint32_t tick;  // the map's tick, which a changed block is stamped with
  // 1 = a colour word with a zero high byte is no colour
  // (ColorFrame::coverage_in_alpha).
  std::uint32_t coverage_in_alpha;
  std::uint32_t fuse_only;  // 1 = a Dynamic set's fuse (Pass::Fuse)
};

// Pin the scalar-block-layout ABI: this struct must stay byte-identical to the
// `PushConstants` block in tsdf_common.glsl. VoxelGridParams is 32 all-scalar
// bytes, so every field lands at its host offset (no std430 vec padding). A
// drift is a compile error, not silent buffer corruption -- the discipline the
// volume/mesh shader-facing PODs already follow.
static_assert(sizeof(PushConstants) == 64, "PushConstants must be 64 bytes");
static_assert(offsetof(PushConstants, grid) == 0, "PushConstants layout drift");
static_assert(offsetof(PushConstants, num_active_blocks) == 32,
              "PushConstants layout drift");
static_assert(offsetof(PushConstants, max_weight) == 36,
              "PushConstants layout drift");
static_assert(offsetof(PushConstants, mode) == 40,
              "PushConstants layout drift");
static_assert(offsetof(PushConstants, has_color) == 44,
              "PushConstants layout drift");
static_assert(offsetof(PushConstants, has_color_attr) == 48,
              "PushConstants layout drift");
static_assert(offsetof(PushConstants, tick) == 52,
              "PushConstants layout drift");
static_assert(offsetof(PushConstants, coverage_in_alpha) == 56,
              "PushConstants layout drift");
static_assert(offsetof(PushConstants, fuse_only) == 60,
              "PushConstants layout drift");

// Whether every entry of a camera the kernel reads is finite. One NaN or
// infinity in a pose or an intrinsic makes every projection NaN, and then no
// frustum bounds the call either.
bool finite(const Mat4f& m) {
  for (int c = 0; c < 4; ++c) {
    for (int r = 0; r < 4; ++r) {
      if (!std::isfinite(m[c][r])) return false;
    }
  }
  return true;
}
bool finite(const ColorCameraParams& cam) {
  return std::isfinite(cam.fx) && std::isfinite(cam.fy) &&
         std::isfinite(cam.cx) && std::isfinite(cam.cy) &&
         finite(cam.cam_to_world);
}
bool finite(const DepthCameraParams& cam) {
  return std::isfinite(cam.fx) && std::isfinite(cam.fy) &&
         std::isfinite(cam.cx) && std::isfinite(cam.cy) &&
         std::isfinite(cam.min_depth) && std::isfinite(cam.max_depth) &&
         finite(cam.cam_to_world);
}

// Where a colour frame's image is: its host pixels or its device buffer (the
// caller has checked that exactly one is set).
core::StorageInput color_input(const ColorFrame& color) noexcept {
  return color.buffer != nullptr ? core::StorageInput(*color.buffer)
                                 : core::StorageInput(color.pixels);
}

// A frustum holding every voxel `cam` can change, or none where the pinhole
// planes are not provably that (DECISIONS.md, 2026-10-06). The kernel changes a
// voxel only if it projects into the image with 0 < zc <= depth + trunc_dist,
// and depth <= max_depth, so: no near cut -- dynamic clears free space up to
// the camera -- and far at max_depth + trunc_dist. make_frustum_planes widens
// the sides by shrinking the focal lengths, which still contains the image only
// while the principal point lies inside it; and it carries the planes to world
// by the pose's inverse-transpose where the kernel uses transpose(R), the same
// for the rigid pose DepthCameraParams requires.
std::optional<volume::FrustumPlanes> fusion_reach(const DepthCameraParams& cam,
                                                  float trunc_dist) {
  if (!(cam.fx > 0.0f && cam.fy > 0.0f && cam.cx >= 0.0f &&
        cam.cx <= static_cast<float>(cam.width) && cam.cy >= 0.0f &&
        cam.cy <= static_cast<float>(cam.height))) {
    return std::nullopt;
  }
  const volume::FrustumPlanes planes = volume::make_frustum_planes(
      cam.fx, cam.fy, cam.cx, cam.cy, cam.width, cam.height, 0.0f,
      cam.max_depth + trunc_dist, cam.cam_to_world);
  for (const Vec4f& p : planes) {
    if (!(std::isfinite(p.x) && std::isfinite(p.y) && std::isfinite(p.z) &&
          std::isfinite(p.w))) {
      return std::nullopt;
    }
  }
  return planes;
}

// This tier's local_size, bound once so every call site reads group_count(n).
std::uint32_t group_count(std::uint32_t items) {
  return core::group_count(items, kLocalSize);
}

