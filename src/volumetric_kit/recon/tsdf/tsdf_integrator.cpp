// The voxel layer's depth camera is a copy of the camera vocabulary's: the same
// fields at the same offsets, so the kernel reads the bytes it read before.
static_assert(
    sizeof(volume::DepthPinhole) == sizeof(sensor::DepthCameraParams) &&
        offsetof(volume::DepthPinhole, fx) ==
            offsetof(sensor::DepthCameraParams, fx) &&
        offsetof(volume::DepthPinhole, fy) ==
            offsetof(sensor::DepthCameraParams, fy) &&
        offsetof(volume::DepthPinhole, cx) ==
            offsetof(sensor::DepthCameraParams, cx) &&
        offsetof(volume::DepthPinhole, cy) ==
            offsetof(sensor::DepthCameraParams, cy) &&
        offsetof(volume::DepthPinhole, min_depth) ==
            offsetof(sensor::DepthCameraParams, min_depth) &&
        offsetof(volume::DepthPinhole, max_depth) ==
            offsetof(sensor::DepthCameraParams, max_depth) &&
        offsetof(volume::DepthPinhole, width) ==
            offsetof(sensor::DepthCameraParams, width) &&
        offsetof(volume::DepthPinhole, height) ==
            offsetof(sensor::DepthCameraParams, height) &&
        offsetof(volume::DepthPinhole, cam_to_world) ==
            offsetof(sensor::DepthCameraParams, cam_to_world),
    "volume::DepthPinhole must keep sensor::DepthCameraParams' layout");

volume::DepthPinhole to_depth_pinhole(
    const sensor::DepthCameraParams& camera) noexcept {
  volume::DepthPinhole out;
  out.fx = camera.fx;
  out.fy = camera.fy;
  out.cx = camera.cx;
  out.cy = camera.cy;
  out.min_depth = camera.min_depth;
  out.max_depth = camera.max_depth;
  out.width = camera.width;
  out.height = camera.height;
  out.cam_to_world = camera.cam_to_world;
  return out;
}

core::Result<TsdfIntegrator> TsdfIntegrator::create(
    core::Device& device, core::Allocator& allocator) {
  VKC_TRY(check_device_requirements(device, "TsdfIntegrator::create"));
  TsdfIntegrator integ;
  integ.device_ = &device;
  integ.allocator_ = &allocator;

  // The integrate and clear kernels, one body (tsdf_integrate.glsl): 10
  // storage-buffer bindings each, one layout for both (0 tsdf, 1 weight,
  // 2 active, 3 depth, 4 depth-camera, 5 color image, 6 color attribute,
  // 7 color camera, 8 the map's block stamps, 9 the active count) + the
  // PushConstants range; and recon's count-to-slices kernel sizing their
  // dispatches (recon::detail::add_dispatch_args). These counts are the
  // single source of truth for
  // both the layouts (KernelSetBuilder::add creates bindings 0..N-1) and the
  // auto-sized pool -- the deliberate cost of the "explicit, not reflected"
  // decision -- so they and the lists above have to move together with the
  // shaders. KernelSetBuilder builds each layout + pipeline and allocates its
  // set from a shared pool (sized to the exact descriptor total).
  VkPushConstantRange push_range{};
  push_range.stageFlags = VK_SHADER_STAGE_COMPUTE_BIT;
  push_range.offset = 0;
  push_range.size = sizeof(PushConstants);
  core::KernelSetBuilder kb(device);
  VKC_TRY(kb.add(integ.kernel_, "tsdf_integrate", vr_tsdf_integrate_comp_spv,
                 vr_tsdf_integrate_comp_spv_size, 10, &push_range));
  VKC_TRY(kb.add(integ.clear_kernel_, "tsdf_clear", vr_tsdf_clear_comp_spv,
                 vr_tsdf_clear_comp_spv_size, 10, &push_range));
  VKC_TRY(recon::detail::add_dispatch_args(kb, integ.args_kernel_,
                                           "tsdf_dispatch_args"));
  VKC_ASSIGN(integ.pool_, kb.build());

  // A 1-D dispatch's groupCountX is capped by maxComputeWorkGroupCount[0] (only
  // >= 65535 is guaranteed, which 32,768 reached blocks pass); cache it so
  // integrate() splits a larger pass into several dispatches.
  VkPhysicalDeviceProperties props{};
  vkGetPhysicalDeviceProperties(device.physical_device(), &props);
  integ.max_workgroup_count_x_ = props.limits.maxComputeWorkGroupCount[0];
  // The device-span collector; see the member's declaration, and GpuTimer for
  // why a pool that will not allocate cannot fail this create().
  VKC_ASSIGN(integ.gpu_timer_, core::GpuTimer::create(device));
  // Likewise for the per-call depth / colour frame uploads, which are bound
  // whole: a frame past this limit is invalid usage, not a slow path.
  integ.max_storage_buffer_range_ = props.limits.maxStorageBufferRange;

  // The camera params are fixed-size, so persist the SSBOs, a frame's every
  // binding-offset alignment, and rewrite them inline in each call's batch
  // -- not a per-call allocation -- and a 1-element dummy for the colour
  // slots a call leaves unused. All of these are device-local, as every
  // buffer the kernel reads is (the 2026-09-28 residency decision). A call
  // writes every binding of every set it dispatches.
  const VkDeviceSize alignment =
      std::max<VkDeviceSize>(props.limits.minStorageBufferOffsetAlignment, 4);
  const auto stride = [alignment](VkDeviceSize bytes) {
    return (bytes + alignment - 1) / alignment * alignment;
  };
  integ.cam_stride_ = stride(sizeof(sensor::DepthCameraParams));
  integ.color_cam_stride_ = stride(sizeof(sensor::ColorCameraParams));
  VKC_ASSIGN(integ.cam_buf_,
             core::device_storage_buffer(allocator, integ.cam_stride_));
  VKC_ASSIGN(integ.color_cam_buf_,
             core::device_storage_buffer(allocator, integ.color_cam_stride_));
  VKC_ASSIGN(integ.color_dummy_,
             core::device_storage_buffer(allocator, sizeof(std::uint32_t)));

  // Name the persistent buffers for a GPU capture. A no-op where the device
  // resolved no debug-utils entry points.
  device.set_object_name(VK_OBJECT_TYPE_BUFFER,
                         core::debug_object_handle(integ.cam_buf_.handle()),
                         "tsdf.depth_cam");
  device.set_object_name(
      VK_OBJECT_TYPE_BUFFER,
      core::debug_object_handle(integ.color_cam_buf_.handle()),
      "tsdf.color_cam");
  device.set_object_name(VK_OBJECT_TYPE_BUFFER,
                         core::debug_object_handle(integ.color_dummy_.handle()),
                         "tsdf.dummy");

  return integ;
}

